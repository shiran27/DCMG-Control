function writeLiteraturePIComparison(r,outdir)
%WRITELITERATUREPICOMPARISON Generate a short, cited manuscript supplement.
s=r.Summary; p=r.LiteratureIndex; c=r.Controllers{p};
fid=fopen(fullfile(outdir,'comparison.tex'),'w'); assert(fid>=0);
cleanup=onCleanup(@()fclose(fid)); %#ok<NASGU>
put(fid,'% Generated by run_literature_pi_comparison.m.');
put(fid,'\subsubsection{Comparison with a passivity-based PI controller}');
put(fid,'We also implement the decentralized multivariable PI voltage controller of Nahata et al.~\cite{Nahata2020}, using its explicit gain region. With $e_{Vi}=V_i-V_{Ei}$ and $e_{Ii}=I_{ti}-I_{tEi}$, its equilibrium-centered realization is');
put(fid,'\begin{align}\dot z_i&=-e_{Vi},\nonumber\\ V_{ti}&=V_{Sti}+k_{1i}e_{Vi}+k_{2i}e_{Ii}+k_{3i}z_i,\label{Eq:LiteraturePI}\end{align}');
put(fid,'where $k_{1i}<1$, $k_{2i}<R_i$, and $0<k_{3i}<(1-k_{1i})(R_i-k_{2i})/L_i$. The baseline uses the same equilibrium, physical plant, initial errors, and disturbances. Its integral deviations start at zero. We verify the published local storage and the coupled resistive-network dissipation inequality, as well as the complete closed-loop poles.');
put(fid,fmt('A saved %d-candidate grid selects $k_{1i}=-%.3g$, $k_{2i}=-%.3g$, and $k_{3i}=%.3g(1-k_{1i})(R_i-k_{2i})/L_i$. Selection minimizes nominal settling time under a %.4g V peak command-deviation budget, equal to the larger nominal peak of the two co-designs; the disturbance tests are not used for tuning.', ...
    height(r.LiteratureTuning.Candidates),c.Options.VoltageGain,c.Options.CurrentGain, ...
    c.Options.IntegralFraction,r.LiteratureTuning.PeakCommandBudget));
put(fid,'\begin{table}[t]\centering\small\caption{Literature comparison: nominal settling time (ms), and disturbance RMS voltage (V), sharing (p.u.), and command deviation (V).}\label{Tab:LiteraturePI}\begin{tabular}{lrrrr}\hline Method & Settling & Voltage & Sharing & Command\\\hline');
indices=[2,3,p]; names={'MB co-design','DD co-design','Passivity PI'};
for j=1:numel(indices)
    k=indices(j);
    put(fid,fmt('%s & %.2f & %.4f & %.5f & %.4f \\',names{j}, ...
        s.SettlingMs(k),s.DisturbanceVoltageRMS(k),s.DisturbanceSharingRMS(k), ...
        s.DisturbanceCommandRMS(k)));
end
put(fid,'\hline\end{tabular}\end{table}');
put(fid,'Figure~\ref{Fig:LiteraturePI} and Table~\ref{Tab:LiteraturePI} compare transient regulation and control effort. A separate persistent-load test adds 0.35 A at every bus at 25 ms while keeping the voltage references fixed. This is a regulation diagnostic, not an $L_2$-gain test.');
put(fid,fmt('Over 100--120 ms, the voltage RMS errors are %.3g V (MB), %.3g V (DD), and %.3g V (PI); the corresponding sharing RMS errors are %.4g, %.4g, and %.4g p.u. The PI integral action enforces zero asymptotic voltage offset, but does not enforce proportional sharing after the load changes. Thus the comparison distinguishes voltage restoration from current-sharing performance. All three controllers use zero communication links here. The PI stability certificate does not provide the synthesized global $L_2$ gain reported for the co-designs.', ...
    s.LoadStepTailVoltageRMS(2),s.LoadStepTailVoltageRMS(3),s.LoadStepTailVoltageRMS(p), ...
    s.LoadStepTailSharingRMS(2),s.LoadStepTailSharingRMS(3),s.LoadStepTailSharingRMS(p)));
put(fid,'\begin{figure*}[t]\centering\includegraphics[width=0.86\textwidth]{Results/LiteraturePI/literature_pi_comparison.pdf}\caption{Comparison with the literature PI baseline on the same continuously coupled ZI microgrid. The additional permanent-load experiment exposes the effect of integral voltage restoration.}\label{Fig:LiteraturePI}\end{figure*}');
clear cleanup
fid=fopen(fullfile(outdir,'RESULTS_SUMMARY.md'),'w'); assert(fid>=0);
cleanup=onCleanup(@()fclose(fid)); %#ok<NASGU>
put(fid,'# Literature PI baseline comparison');
put(fid,'Source: Nahata et al., Automatica 113 (2020), 108770. https://doi.org/10.1016/j.automatica.2019.108770');
put(fid,'Run `run_all_paper_results` or `main.mlx` to rebuild all controllers, results, and regression checks. To reuse the verified core gains while regenerating the PI design and every comparison response, run `run_literature_pi_comparison`.');
put(fid,'');
put(fid,'| Method | Settling ms | Pulse voltage RMS V | Pulse sharing RMS pu | Pulse command RMS V | Load-step tail voltage RMS V | Load-step tail sharing RMS pu |');
put(fid,'|---|---:|---:|---:|---:|---:|---:|');
for k=1:height(s)
    put(fid,fmt('| %s | %.2f | %.5f | %.5f | %.5f | %.6g | %.5f |',s.Method(k), ...
        s.SettlingMs(k),s.DisturbanceVoltageRMS(k),s.DisturbanceSharingRMS(k), ...
        s.DisturbanceCommandRMS(k),s.LoadStepTailVoltageRMS(k),s.LoadStepTailSharingRMS(k)));
end
put(fid,'');
put(fid,fmt('Selected kp=%.3g, kd=%.3g, integral fraction=%.3g; %d of %d candidates pass. Nominal peak-command budget: %.6g V.', ...
    c.Options.VoltageGain,c.Options.CurrentGain,c.Options.IntegralFraction, ...
    nnz(r.LiteratureTuning.Candidates.Accepted),height(r.LiteratureTuning.Candidates), ...
    r.LiteratureTuning.PeakCommandBudget));
put(fid,fmt('Independent ODE residual: %.3g. Absolute-law residual: %.3g. Local/network passivity checks, constant-load equilibrium check, matched input check, and peak budget check: passed.', ...
    r.Checks.ODEResidual,r.Checks.AbsoluteLawResidual));
put(fid,'The constant-load test holds the pre-change references fixed. The PI controller regulates each voltage to that reference; proportional sharing under a changed load would need a separate secondary layer. No L2 bound is claimed for PI.');
end

function put(fid,line)
fprintf(fid,'%s\n',line);
end

function text=fmt(format,varargin)
text=sprintf(strrep(format,'\','\\'),varargin{:});
% Scientific notation must remain valid in LaTeX text as well as Markdown.
if contains(text,'$') || contains(text,' V (')
    [tokens,matches]=regexp(text,'([0-9]+(?:\.[0-9]+)?)e([+-]?[0-9]+)','tokens','match');
    for k=1:numel(tokens)
        text=strrep(text,matches{k},['$',tokens{k}{1},'\times10^{', ...
            num2str(str2double(tokens{k}{2})),'}$']);
    end
end
end
